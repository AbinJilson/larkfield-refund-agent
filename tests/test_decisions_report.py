"""Run every gold extraction through decide and write the review table."""

from __future__ import annotations

from pathlib import Path

import pytest

from src.decide import process_extraction

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "tests" / "output" / "decisions.md"


def _decisions(tickets, gold, data, config, extraction_from_gold):
    rows = []
    for ticket_id in sorted(gold):
        extraction = extraction_from_gold(gold[ticket_id], ticket_id)
        result = process_extraction(
            tickets[ticket_id], extraction, data, config=config
        )
        rows.append(result)
    return rows


def test_gold_extractions_reproduce_the_15_labels(
    tickets, gold, labels, data, config, extraction_from_gold
):
    results = {
        result.ticket_id: result
        for result in _decisions(
            tickets, gold, data, config, extraction_from_gold
        )
    }
    for ticket_id, label in labels.items():
        result = results[ticket_id]
        assert result.outcome == label["expected_outcome"], ticket_id
        assert result.approver_role == label["expected_approver_role"], ticket_id
        assert (
            result.human_approval_required
            is label["expected_human_approval_required"]
        ), ticket_id


def test_all_40_gold_extractions_write_the_decisions_table(
    tickets, gold, data, config, extraction_from_gold
):
    results = _decisions(tickets, gold, data, config, extraction_from_gold)

    assert len(results) == 40
    assert {result.ticket_id for result in results} == set(gold)

    lines = [
        "# Decisions from the gold extractions",
        "",
        (
            "Generated by `tests/test_decisions_report.py` from "
            "`tests/fixtures/gold_extractions.json`. Amount is the 2.5 "
            "remaining amount on the ledger REFUND row."
        ),
        "",
        (
            "Each ticket is run on its own, so no earlier ledger row is "
            "passed in. T027 and T028 are re-sends of T002 and T005: when the "
            "earlier REFUND row is in the ledger they become REJECT / "
            "ALREADY_REFUNDED (NOTES.md ruling 1)."
        ),
        "",
        "| Ticket | Rule | Outcome | Amount | Reason codes |",
        "|---|---:|---|---:|---|",
    ]
    for result in results:
        amount = f"{result.amount:.2f}" if result.amount is not None else "—"
        reasons = ", ".join(result.reason_codes) if result.reason_codes else "—"
        lines.append(
            f"| {result.ticket_id} | {result.rule_id} | {result.outcome} | "
            f"{amount} | {reasons} |"
        )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    text = OUTPUT.read_text(encoding="utf-8")
    assert text.startswith("# Decisions from the gold extractions")
    for ticket_id in gold:
        assert f"| {ticket_id} |" in text


@pytest.mark.parametrize("ticket_id", ["T001", "T011", "T024", "T026", "P05"])
def test_gold_decision_spot_checks(
    ticket_id, tickets, gold, data, config, extraction_from_gold
):
    result = process_extraction(
        tickets[ticket_id],
        extraction_from_gold(gold[ticket_id], ticket_id),
        data,
        config=config,
    )
    assert result.outcome in {
        "PROCEED",
        "PROCEED_MODIFIED",
        "PEND",
        "ESCALATE",
        "REJECT",
        "INVALID_REQUEST",
        "UNABLE_TO_VERIFY",
    }
    assert 1 <= result.rule_id <= 14
